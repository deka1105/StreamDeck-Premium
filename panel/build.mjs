// Builds the panel into ONE self-contained HTML file (inline JS + CSS), plus:
//   dist/panel.html                      served by the desktop host (/panel/)
//   dist/catalog.json                    the widget catalogue (editor + host validation)
//   ../mobile/src/generated/panelHtml.ts the same HTML, bundled into the phone app
//
// Run: npm run build   (in panel/)

import { build } from "esbuild";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dist = join(here, "dist");
const mobileGen = join(here, "..", "mobile", "src", "generated");

async function bundle(entry) {
  const out = await build({
    entryPoints: [join(here, entry)],
    bundle: true,
    format: "iife",
    minify: true,
    target: ["es2019", "safari13", "chrome80"],
    write: false,
    legalComments: "none",
  });
  // Never let the script close its own <script> tag early.
  return out.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
}

export async function buildPanel() {
  const js = await bundle("src/index.js");
  const css = readFileSync(join(here, "src", "style.css"), "utf8");
  const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover">
<title>DeskAssist panel</title>
<style>${css}</style>
</head>
<body>
<div id="status"></div>
<div id="banner" hidden></div>
<div id="pages"></div>
<nav id="dots" hidden></nav>
<button id="timerBadge" hidden></button>
<div id="overview" hidden></div>
<div id="alarm" hidden></div>
<div id="switch" hidden></div>
<div id="toasts" aria-live="polite"></div><div id="prompts" hidden></div>
<script>${js}</script>
</body>
</html>
`;
  const { catalog } = await import("./src/widgets/index.js");
  const { TEMPLATES } = await import("./src/templates.js");
  const editorJs = await bundle("editor/index.js");
  const editorCss = readFileSync(join(here, "editor", "editor.css"), "utf8");
  const editorHtml = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>DeskAssist — layout editor</title>
<style>${editorCss}</style>
</head>
<body>
<header>
  <h1>DeskAssist layout</h1>
  <select id="target" aria-label="Device"></select>
  <span id="rev"></span>
  <span class="spacer"></span>
  <button id="settingsToggle" aria-pressed="false">Settings</button>
  <button id="previewToggle" aria-pressed="false">Live preview</button>
  <button id="revert" disabled>Revert</button>
  <button id="save" class="primary" disabled>Save</button>
</header>
<main>
  <aside><h2>Pages</h2><div id="pages"></div><div id="pageSettings"></div></aside>
  <section id="center">
    <div id="canvas"></div>
    <iframe id="previewFrame" title="Live preview" hidden></iframe>
    <div id="settingsView" hidden></div>
    <p class="hint">Drag a widget to move it, drag its corner to resize. Delete removes the selected widget. ⌘/Ctrl-S saves.</p>
  </section>
  <aside class="right"><h2>Add a widget</h2><div id="palette"></div><h2 style="margin-top:20px">Selected widget</h2><div id="inspector"></div></aside>
</main>
<div id="flash" hidden></div>
<script>${editorJs}</script>
</body>
</html>
`;
  mkdirSync(dist, { recursive: true });
  mkdirSync(mobileGen, { recursive: true });
  writeFileSync(join(dist, "panel.html"), html);
  writeFileSync(join(dist, "editor.html"), editorHtml);
  writeFileSync(join(dist, "catalog.json"), JSON.stringify(catalog(), null, 2) + "\n");
  writeFileSync(join(dist, "templates.json"), JSON.stringify({ version: 1, templates: TEMPLATES }, null, 2) + "\n");
  writeFileSync(
    join(mobileGen, "panelHtml.ts"),
    `// GENERATED by panel/build.mjs — do not edit. Run \`npm run build\` in panel/.\n` +
      `export const PANEL_HTML: string = ${JSON.stringify(html)};\n`,
  );
  return { bytes: html.length };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { bytes } = await buildPanel();
  console.log(`panel built: dist/panel.html (${(bytes / 1024).toFixed(1)} KB), dist/catalog.json, mobile/src/generated/panelHtml.ts`);
}
