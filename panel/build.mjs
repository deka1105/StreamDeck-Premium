// Builds the panel into ONE self-contained HTML file (inline JS + CSS), plus:
//   dist/panel.html                      served by the desktop host (/panel/)
//   dist/catalog.json                    the widget catalogue (editor + host validation)
//   ../mobile/src/generated/panelHtml.ts the same HTML, bundled into the phone app
//
// Run: npm run build   (in panel/)

import { build } from "esbuild";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dist = join(here, "dist");
const mobileGen = join(here, "..", "mobile", "src", "generated");

async function bundle(entry) {
  const out = await build({
    entryPoints: [join(here, entry)],
    bundle: true,
    format: "iife",
    minify: true,
    target: ["es2019", "safari13", "chrome80"],
    write: false,
    legalComments: "none",
  });
  // Never let the script close its own <script> tag early.
  return out.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
}

export async function buildPanel() {
  const js = await bundle("src/index.js");
  const css = readFileSync(join(here, "src", "style.css"), "utf8");
  const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover">
<title>DeskAssist panel</title>
<style>${css}</style>
</head>
<body>
<div id="status"></div>
<div id="banner" hidden></div>
<div id="pages"></div>
<nav id="dots" hidden></nav>
<div id="overview" hidden></div>
<script>${js}</script>
</body>
</html>
`;
  const { catalog } = await import("./src/widgets/index.js");
  mkdirSync(dist, { recursive: true });
  mkdirSync(mobileGen, { recursive: true });
  writeFileSync(join(dist, "panel.html"), html);
  writeFileSync(join(dist, "catalog.json"), JSON.stringify(catalog(), null, 2) + "\n");
  writeFileSync(
    join(mobileGen, "panelHtml.ts"),
    `// GENERATED by panel/build.mjs — do not edit. Run \`npm run build\` in panel/.\n` +
      `export const PANEL_HTML: string = ${JSON.stringify(html)};\n`,
  );
  return { bytes: html.length };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { bytes } = await buildPanel();
  console.log(`panel built: dist/panel.html (${(bytes / 1024).toFixed(1)} KB), dist/catalog.json, mobile/src/generated/panelHtml.ts`);
}
