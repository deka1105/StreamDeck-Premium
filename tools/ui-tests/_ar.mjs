import { chromium } from "@playwright/test";
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 844, height: 390 }, deviceScaleFactor: 2, locale: "ar-SA" });
const errs = [];
p.on("pageerror", (e) => errs.push(e.message));
await p.goto("file://" + process.env.PANEL);
await p.waitForTimeout(1200);
await p.screenshot({ path: process.argv[2] + "-home.png" });
const i = await p.evaluate(() => [...document.querySelectorAll("#dots .dot")].map((d) => d.getAttribute("aria-label")).indexOf("Studio"));
await p.locator("#dots .dot").nth(i).click();
await p.waitForTimeout(2000);
await p.screenshot({ path: process.argv[2] + "-studio.png" });
console.log("dir:", await p.evaluate(() => document.documentElement.dir), "errors:", JSON.stringify(errs));
await b.close();
